import { Buffer } from 'node:buffer';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, extname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';
import { format } from 'prettier';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const defaultDist = join(repoRoot, 'apps/panel/dist');
const defaultOutput = join(repoRoot, 'deploy/worker/src/generated/panelAssets.ts');

const contentTypes = new Map([
  ['.js', 'text/javascript; charset=utf-8'],
  ['.css', 'text/css; charset=utf-8'],
  ['.svg', 'image/svg+xml; charset=utf-8'],
  ['.json', 'application/json; charset=utf-8'],
  ['.txt', 'text/plain; charset=utf-8'],
  ['.map', 'application/json; charset=utf-8'],
]);

function assertLocalOnly(value, source) {
  const external =
    /(?:src|href)\s*=\s*["']https?:\/\/|url\(\s*["']?https?:\/\/|@import\s+(?:url\()?\s*["']?https?:\/\//iu;
  if (external.test(value)) throw new Error(`external-panel-asset:${source}`);
}

async function walk(dir) {
  const result = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) result.push(...(await walk(path)));
    else result.push(path);
  }
  return result.sort((a, b) => a.localeCompare(b));
}

export async function generatePanelAssets({
  distDir = defaultDist,
  outputFile = defaultOutput,
} = {}) {
  const indexPath = join(distDir, 'index.html');
  const html = await readFile(indexPath, 'utf8');
  assertLocalOnly(html, 'index.html');
  const assets = {};
  for (const path of await walk(distDir)) {
    if (path === indexPath) continue;
    const extension = extname(path).toLowerCase();
    const contentType = contentTypes.get(extension);
    if (!contentType) throw new Error(`unsupported-panel-asset:${relative(distDir, path)}`);
    const body = await readFile(path, 'utf8');
    if (extension === '.css') assertLocalOnly(body, relative(distDir, path));
    const rel = relative(distDir, path).split(sep).join('/');
    assets[`/panel-assets/${rel}`] = { contentType, body };
  }
  const lines = [
    '// Generated by scripts/build-panel-assets.mjs. Do not edit by hand.',
    `export const PANEL_INDEX_HTML = ${JSON.stringify(html)};`,
    'export const PANEL_ASSETS: Record<string, { contentType: string; body: string }> =',
    `${JSON.stringify(assets, null, 2)};`,
    '',
  ];
  await mkdir(dirname(outputFile), { recursive: true });
  const formatted = await format(lines.join('\n'), {
    parser: 'typescript',
    singleQuote: true,
    trailingComma: 'all',
    printWidth: 100,
  });
  await writeFile(outputFile, formatted);
  return { indexBytes: Buffer.byteLength(html), assetCount: Object.keys(assets).length };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  generatePanelAssets()
    .then((result) => {
      process.stdout.write(
        `Embedded panel assets: ${result.assetCount} files, ${result.indexBytes} index bytes\n`,
      );
    })
    .catch((error) => {
      process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
      process.exitCode = 1;
    });
}
