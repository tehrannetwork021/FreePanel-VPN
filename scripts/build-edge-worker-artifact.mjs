import { Buffer } from 'node:buffer';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { build } from 'esbuild';

const root = resolve(import.meta.dirname, '..');
const entry = resolve(root, 'deploy/worker/src/index.ts');
const packageJson = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
const version = String(packageJson.version);

const result = await build({
  entryPoints: [entry],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  external: ['cloudflare:sockets'],
  legalComments: 'none',
  charset: 'utf8',
});

if (result.outputFiles.length !== 1) {
  throw new Error('expected-single-worker-artifact');
}

const source = result.outputFiles[0].text;
const sha256 = createHash('sha256').update(source).digest('hex');
const bytes = Buffer.byteLength(source);

const generatedPath = resolve(root, 'apps/installer-worker/src/generated/edgeWorkerArtifact.ts');
const manifestPath = resolve(root, 'dist/installer-artifacts/edge-worker-manifest.json');
const rawBundlePath = resolve(root, 'dist/edge-worker.js');
await mkdir(dirname(generatedPath), { recursive: true });
await mkdir(dirname(manifestPath), { recursive: true });
await mkdir(dirname(rawBundlePath), { recursive: true });

const generated = [
  '// Generated by scripts/build-edge-worker-artifact.mjs. Do not edit.',
  `export const EDGE_WORKER_VERSION = ${JSON.stringify(version)};`,
  `export const EDGE_WORKER_SHA256 = ${JSON.stringify(sha256)};`,
  `export const EDGE_WORKER_SOURCE = ${JSON.stringify(source)};`,
  '',
].join('\n');
const manifest = { version, sha256, bytes, file: 'edge-worker.js' };

await writeFile(generatedPath, generated, 'utf8');
await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
await writeFile(rawBundlePath, source, 'utf8');
